const crypto = require('node:crypto')
const fs = require('node:fs')
const path = require('node:path')

const projectRoot = path.resolve(__dirname, '..')
const publicRoot = path.join(projectRoot, 'public', 'camila')
const outputFile = path.join(projectRoot, 'data', 'public-image-manifest.js')
const allowedCategories = {
  fashion: 'Fashion',
  fitness: 'Fitness',
  lifestyle: 'Lifestyle',
  travel: 'Travel',
  unclassified: 'Other',
}
const allowedExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif'])
const seenHashes = new Map()

function toLabel(fileName) {
  return path.basename(fileName, path.extname(fileName))
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\p{L}/gu, (letter) => letter.toUpperCase())
}

function getImages(category, title) {
  const categoryDirectory = path.join(publicRoot, category)
  if (!fs.existsSync(categoryDirectory)) return []

  return fs.readdirSync(categoryDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && allowedExtensions.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right, 'en'))
    .map((fileName) => {
      const absolutePath = path.join(categoryDirectory, fileName)
      const hash = crypto.createHash('sha256').update(fs.readFileSync(absolutePath)).digest('hex')
      const previous = seenHashes.get(hash)
      if (previous) {
        throw new Error(`Duplicate public image bytes found: ${previous} and ${category}/${fileName}`)
      }
      seenHashes.set(hash, `${category}/${fileName}`)

      const label = toLabel(fileName)
      return {
        id: `${category}-${hash.slice(0, 12)}`,
        category,
        categoryTitle: title,
        src: `/camila/${category}/${fileName}`,
        alt: `${title}: ${label}`,
        caption: label,
      }
    })
}

if (!fs.existsSync(publicRoot)) {
  throw new Error(`Public Camila image directory does not exist: ${publicRoot}`)
}

const imageMap = Object.fromEntries(
  Object.entries(allowedCategories).map(([category, title]) => [category, getImages(category, title)])
)

const output = [
  '// Generated by scripts/generate-public-image-manifest.js; do not edit manually.',
  '// Gallery image source folders are public/camila/{fashion,fitness,lifestyle,travel,unclassified}. Hero slides are maintained separately.',
  `export const publicCategoryImages = ${JSON.stringify(imageMap, null, 2)}`,
  '',
].join('\n')

fs.writeFileSync(outputFile, output, 'utf8')
const counts = Object.entries(imageMap).map(([category, images]) => `${category}=${images.length}`).join(', ')
console.log(`Generated ${path.relative(projectRoot, outputFile)} (${counts}).`)
console.log('Private Review, hero, and premium-preview folders are excluded from the public category/gallery manifest.')
